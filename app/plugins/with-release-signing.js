const {withAppBuildGradle} = require('@expo/config-plugins')

const MARKER = '// Pnyx release signing.'

const STORE_FILE = 'PNYX_RELEASE_STORE_FILE'
const STORE_PASSWORD = 'PNYX_RELEASE_STORE_PASSWORD'
const KEY_ALIAS = 'PNYX_RELEASE_KEY_ALIAS'
const KEY_PASSWORD = 'PNYX_RELEASE_KEY_PASSWORD'
const STORE_TYPE = 'PNYX_RELEASE_STORE_TYPE'

const MISSING_MESSAGE =
  'Release signing is not configured. Set ' +
  `${STORE_FILE}, ${STORE_PASSWORD}, ${KEY_ALIAS} and ${KEY_PASSWORD} ` +
  'in ~/.gradle/gradle.properties (or pass them with -P). ' +
  'See docs/ANDROID_SIGNING.md.'

/**
 * Declarations the signing config and the guard both read. Placed above `android {` so the
 * `signingConfigs` and `buildTypes` closures capture them from the script scope.
 *
 * `findProperty` rather than a bare reference: an absent gradle property raises
 * MissingPropertyException at *configuration* time, which would break `assembleDebug` too.
 */
const declarations = `${MARKER} Credentials come from gradle properties, never from this file:
// android/ is generated by prebuild and the repo carries no key and no home path.
def pnyxReleaseStoreFile = findProperty('${STORE_FILE}')
def pnyxReleaseStorePassword = findProperty('${STORE_PASSWORD}')
def pnyxReleaseKeyAlias = findProperty('${KEY_ALIAS}')
def pnyxReleaseKeyPassword = findProperty('${KEY_PASSWORD}')
def pnyxReleaseSigning = pnyxReleaseStoreFile != null && pnyxReleaseStorePassword != null &&
    pnyxReleaseKeyAlias != null && pnyxReleaseKeyPassword != null

// Fail the build rather than fall back to the debug key. A release APK signed with the template's
// public key can be "updated" by anyone, and swapping to a real key later forces an uninstall,
// which destroys the keystore-held seed. Checked on the task graph so debug builds stay usable.
gradle.taskGraph.whenReady { graph ->
    if (!pnyxReleaseSigning && graph.allTasks.any { it.project == project && it.name.endsWith('Release') }) {
        throw new GradleException('${MISSING_MESSAGE}')
    }
}

`

/**
 * The guarded `release` signing config, indented to sit inside `signingConfigs`.
 */
function releaseSigningLines(indent) {
  return [
    `${indent}if (pnyxReleaseSigning) {`,
    `${indent}    release {`,
    `${indent}        storeFile file(pnyxReleaseStoreFile)`,
    `${indent}        storePassword pnyxReleaseStorePassword`,
    `${indent}        keyAlias pnyxReleaseKeyAlias`,
    `${indent}        keyPassword pnyxReleaseKeyPassword`,
    `${indent}        storeType findProperty('${STORE_TYPE}') ?: 'PKCS12'`,
    `${indent}    }`,
    `${indent}}`,
  ]
}

/**
 * Index just past the `{` that opens `header`'s block, searching from `from`.
 */
function openBraceAfter(contents, header, from) {
  const at = contents.indexOf(header, from)
  if (at === -1) return -1
  const brace = contents.indexOf('{', at)
  return brace === -1 ? -1 : brace + 1
}

/**
 * Index of the `}` closing the block that starts at `open`, respecting nesting.
 */
function closeBraceOf(contents, open) {
  let depth = 1
  for (let i = open; i < contents.length; i++) {
    if (contents[i] === '{') depth++
    else if (contents[i] === '}' && --depth === 0) return i
  }
  return -1
}

/**
 * Point `buildTypes.release` at the release signing config.
 *
 * Scanned rather than string-replaced: `signingConfig signingConfigs.debug` appears in both the
 * `debug` and `release` build types, and only the second one may move.
 */
function repointReleaseBuildType(contents) {
  const buildTypes = openBraceAfter(contents, 'buildTypes', 0)
  if (buildTypes === -1) throw new Error('with-release-signing: no buildTypes block in the app build.gradle')

  const release = openBraceAfter(contents, 'release', buildTypes)
  const buildTypesEnd = closeBraceOf(contents, buildTypes)
  if (release === -1 || release > buildTypesEnd) {
    throw new Error('with-release-signing: no release build type in the app build.gradle')
  }
  const releaseEnd = closeBraceOf(contents, release)

  const body = contents.slice(release, releaseEnd)
  if (!body.includes('signingConfig ')) {
    throw new Error('with-release-signing: the release build type declares no signingConfig')
  }

  // `null` when unset: AGP configures fine and leaves the APK unsigned, and the task-graph guard
  // above turns that into a build failure before anything is produced.
  const repointed = body.replace(/signingConfig .*/, 'signingConfig pnyxReleaseSigning ? signingConfigs.release : null')
  return contents.slice(0, release) + repointed + contents.slice(releaseEnd)
}

function addReleaseSigningConfig(contents) {
  const open = openBraceAfter(contents, 'signingConfigs', 0)
  if (open === -1) {
    throw new Error('with-release-signing: no signingConfigs block in the app build.gradle')
  }
  const close = closeBraceOf(contents, open)
  if (close === -1) throw new Error('with-release-signing: the signingConfigs block is not closed')

  // Insert before the whole closing-brace line, so that line keeps its own indentation.
  const lineStart = contents.lastIndexOf('\n', close) + 1
  const indent = contents.slice(lineStart, close)
  if (/\S/.test(indent)) {
    throw new Error('with-release-signing: the signingConfigs block does not close on its own line')
  }

  const block = `${releaseSigningLines(`${indent}    `).join('\n')}\n`
  return contents.slice(0, lineStart) + block + contents.slice(lineStart)
}

function injectReleaseSigning(contents) {
  // A prebuild without --clean re-runs this over a build.gradle it already edited.
  if (contents.includes(MARKER)) return contents

  const anchor = /^android \{/m
  if (!anchor.test(contents)) throw new Error('with-release-signing: no android block in the app build.gradle')

  const withDeclarations = contents.replace(anchor, `${declarations}android {`)
  return repointReleaseBuildType(addReleaseSigningConfig(withDeclarations))
}

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error('with-release-signing: expected a Groovy app build.gradle')
    }
    config.modResults.contents = injectReleaseSigning(config.modResults.contents)
    return config
  })
}

module.exports.MARKER = MARKER
module.exports.MISSING_MESSAGE = MISSING_MESSAGE
module.exports.injectReleaseSigning = injectReleaseSigning
