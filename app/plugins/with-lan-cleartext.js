const fs = require('node:fs')
const path = require('node:path')
const {withAndroidManifest, withDangerousMod} = require('@expo/config-plugins')

/**
 * Permit cleartext HTTP to ONE LAN host, for testing a release-shaped build against a service
 * running on the dev machine.
 *
 * Why it is needed: `usesCleartextTraffic="true"` lives only in the `debug` / `debugOptimized`
 * manifests, so a preview or production APK refuses plain `http://` outright — a request to
 * `http://192.168.x.x:3300` fails inside the app before it reaches the network, which reads as "the
 * service is down" rather than "the platform blocked it".
 *
 * Why not `expo-build-properties`' `usesCleartextTraffic`: that is a global switch. This emits a
 * network-security config whose base policy still **forbids** cleartext and carves out the single
 * host given, so nothing else in the app silently gains permission to talk plaintext.
 *
 * Inert unless `host` is set, which is what keeps it out of production: no `PNYX_LAN_HOST`, no
 * config file, no manifest attribute, platform default applies.
 *
 * ⚠️ Android only. iOS App Transport Security blocks the same request and needs
 * `NSAllowsLocalNetworking`; add it here if an iOS LAN preview is ever wanted.
 */
const CONFIG_NAME = 'network_security_config'

const xml = (host) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-lan-cleartext.js from PNYX_LAN_HOST. Do not edit: prebuild rewrites it. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">${host}</domain>
  </domain-config>
</network-security-config>
`

module.exports = function withLanCleartext(config, {host} = {}) {
  if (!host) {
    return config
  }

  const withFile = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml')
      fs.mkdirSync(dir, {recursive: true})
      fs.writeFileSync(path.join(dir, `${CONFIG_NAME}.xml`), xml(host))
      return cfg
    },
  ])

  return withAndroidManifest(withFile, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0]
    if (application) {
      application.$['android:networkSecurityConfig'] = `@xml/${CONFIG_NAME}`
    }
    return cfg
  })
}
