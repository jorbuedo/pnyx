#!/usr/bin/env bun
/**
 * Build production release artifacts.
 *
 * Produces deployable artifacts for each platform:
 *   - android: Release APK at android/app/build/outputs/apk/release/app-release.apk
 *   - ios: Release archive via xcodebuild
 *   - web: Static export at dist/
 *
 * Usage:
 *   bun scripts/build.ts android              (same as --env=dev)
 *   bun scripts/build.ts android --env=prod   (production release)
 *   bun scripts/build.ts android --env=preview
 *   bun scripts/build.ts android --env=preview
 *   bun scripts/build.ts ios
 *   bun scripts/build.ts ios --simulator        (unsigned .app for the Simulator → dist/)
 *   bun scripts/build.ts web
 *
 * @module
 */

import {execSync} from 'node:child_process'
import {mkdirSync, rmSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {appEnvFileVars, buildEnvFor, disableSentryUploadUnlessConfigured, ensureEnv, lanServiceUrl} from './ensure-env'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')

type Platform = 'ios' | 'android' | 'web'
const VALID_PLATFORMS: Platform[] = ['ios', 'android', 'web']

const VALID_ENVS = ['dev', 'preview', 'prod'] as const
type BuildEnv = (typeof VALID_ENVS)[number]

/**
 * Translate the user-facing `--env=<x>` into the two axes `app.config.js`
 * expects: `PNYX_BUILD_VARIANT` (app identity) and `PNYX_APP_ENV`
 * (runtime tag). Mirrors the EAS preview path and the extension build's
 * spawn-env shape so a local `bun scripts/build.ts <platform> --env=preview`
 * produces the same prod-shaped artifact + `preview` telemetry tag as
 * the EAS preview build.
 */
function envForExpo(buildEnv: BuildEnv): NodeJS.ProcessEnv {
  const buildVariantForExpo = buildEnv === 'preview' ? 'prod' : buildEnv
  return {
    // The variant's backend (`env/.env.<variant>`) outranks the developer's `.env`; a deliberate
    // shell export still wins. See buildEnvFor for why the obvious spread order is wrong under Bun.
    ...buildEnvFor({...appEnvFileVars(buildEnv), ...lanServiceUrl()}),
    PNYX_BUILD_VARIANT: buildVariantForExpo,
    PNYX_APP_ENV: buildEnv,
  }
}

function buildAndroid(buildEnv: BuildEnv): void {
  const env = envForExpo(buildEnv)

  console.log('Running expo prebuild for Android...')
  execSync('npx expo prebuild --platform android --clean', {cwd: ROOT, stdio: 'inherit', env})

  console.log('Building release APK with Gradle...')
  execSync('./gradlew assembleRelease', {cwd: join(ROOT, 'android'), stdio: 'inherit', env})

  const apkPath = 'android/app/build/outputs/apk/release/app-release.apk'
  console.log(`\nRelease APK: ${apkPath}`)
}

/**
 * `--simulator` builds for the iOS Simulator instead of a device.
 *
 * ⚠️ **This is the only iOS artifact that can be handed to someone who is not on our Apple team.**
 * A simulator build is not code-signed at all, so it needs no provisioning profile and no
 * membership. A *device* build does, and a free "Personal Team" cannot substitute: its profiles
 * expire after 7 days and it may not sign the entitlements this app declares in `app.config.js`
 * (`associatedDomains` — the passkey rail and deep links — and `aps-environment`). A build with
 * those stripped would look like Pnyx with its recovery broken, which is worse than no build.
 *
 * What the simulator cannot do, so nobody reports it as a bug: no Secure Enclave (the vault falls
 * back to software), no push, no passkeys, no camera.
 */
function buildIos(buildEnv: BuildEnv, simulator: boolean): void {
  if (process.platform !== 'darwin') {
    console.error('iOS builds require macOS with Xcode.')
    process.exit(1)
  }

  const env = envForExpo(buildEnv)

  console.log('Running expo prebuild for iOS...')
  execSync('npx expo prebuild --platform ios --clean', {cwd: ROOT, stdio: 'inherit', env})

  const iosDir = join(ROOT, 'ios')

  // Find the Xcode workspace generated by expo prebuild
  const files = require('node:fs').readdirSync(iosDir) as string[]
  const found = files.find((f: string) => f.endsWith('.xcworkspace'))
  if (!found) {
    console.error('No Xcode workspace found in ios directory')
    process.exit(1)
  }
  const workspace = join(iosDir, found)
  const scheme = found.replace('.xcworkspace', '')

  if (simulator) {
    console.log(`Building simulator app (${scheme})...`)
    execSync(
      `xcodebuild -workspace "${workspace}" -scheme "${scheme}" -configuration Release ` +
        `-sdk iphonesimulator -destination 'generic/platform=iOS Simulator' ` +
        `-derivedDataPath build/sim CODE_SIGNING_ALLOWED=NO`,
      {cwd: iosDir, stdio: 'inherit', env},
    )

    const app = join(iosDir, `build/sim/Build/Products/Release-iphonesimulator/${scheme}.app`)
    const outDir = join(ROOT, 'dist')
    const zip = join(outDir, 'pnyx-simulator.zip')
    mkdirSync(outDir, {recursive: true})
    rmSync(zip, {force: true})
    // `ditto` rather than `zip`: it is what Apple's own tooling uses and it preserves the bundle's
    // symlinks and resource forks, which a plain `zip -r` mangles.
    execSync(`ditto -c -k --sequesterRsrc --keepParent "${app}" "${zip}"`, {stdio: 'inherit'})

    console.log(`\nSimulator app: ${zip}`)
    console.log('  Run it with:  xcrun simctl install booted <unzipped>.app')
    return
  }

  console.log(`Building release archive (${scheme})...`)
  execSync(
    `xcodebuild -workspace "${workspace}" -scheme "${scheme}" -configuration Release -destination 'generic/platform=iOS' -archivePath build/${scheme}.xcarchive archive`,
    {cwd: iosDir, stdio: 'inherit', env},
  )

  console.log(`\nRelease archive: ios/build/${scheme}.xcarchive`)
}

function buildWeb(buildEnv: BuildEnv): void {
  const env = {
    ...envForExpo(buildEnv),
    NODE_OPTIONS: [process.env.NODE_OPTIONS, '--max-old-space-size=8192'].filter(Boolean).join(' '),
  }

  console.log('Exporting web app...')
  execSync('npx expo export --platform web', {cwd: ROOT, stdio: 'inherit', env})

  console.log('\nWeb export: dist/')
}

// -- Main -------------------------------------------------------------------

const args = process.argv.slice(2)
const platform = args.find((arg) => !arg.startsWith('--')) as Platform | undefined

const envArg = args.find((a) => a.startsWith('--env='))
const envValue = envArg?.slice(6)
if (envValue !== undefined && !(VALID_ENVS as readonly string[]).includes(envValue)) {
  console.error(`Invalid --env value: "${envValue}". Valid values: ${VALID_ENVS.join(', ')}.`)
  process.exit(1)
}
// Default to 'dev' by design — an unspecified build should never silently
// produce a production artifact. Use --env=prod explicitly for production.
const buildEnv = (envValue as BuildEnv | undefined) ?? 'dev'

if (!platform || !VALID_PLATFORMS.includes(platform)) {
  console.error('Usage: bun scripts/build.ts <platform> [--env=dev|preview|prod] [--simulator]')
  console.error('Platforms:', VALID_PLATFORMS.join(', '))
  process.exit(1)
}

console.log(`\nBuilding ${platform} (env: ${buildEnv})...\n`)

ensureEnv()
disableSentryUploadUnlessConfigured()

switch (platform) {
  case 'android':
    buildAndroid(buildEnv)
    break
  case 'ios':
    buildIos(buildEnv, args.includes('--simulator'))
    break
  case 'web':
    buildWeb(buildEnv)
    break
}

console.log(`\n${platform} (env: ${buildEnv}) build complete!\n`)
