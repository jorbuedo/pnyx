#!/usr/bin/env bun
/**
 * Build development APK/IPA for testing on physical devices.
 *
 * This creates a debug build with expo-dev-client that can connect
 * to the metro bundler via QR code for hot reloading.
 *
 * Usage:
 *   bun scripts/build-dev.ts android   # Build Android debug APK
 *   bun scripts/build-dev.ts ios       # Build iOS (requires Mac + Xcode)
 *
 * After building:
 *   1. Install the APK/app on your device
 *   2. Run `bun run dev` to start metro
 *   3. Scan the QR code in the terminal with your device
 *
 * @module
 */

import {execSync} from 'node:child_process'
import {cpSync, existsSync, mkdirSync, readdirSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {assertDevEnvComplete, ensureEnv} from './ensure-env'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')

type Platform = 'android' | 'ios'

/**
 * Build development APK for Android.
 */
async function buildAndroid(): Promise<void> {
  const env = {...process.env, PNYX_BUILD_VARIANT: 'devclient'}

  console.log('\n📱 Building Android development APK...\n')

  // Step 1: Run expo prebuild
  console.log('Step 1/3: Running expo prebuild...')
  execSync('npx expo prebuild --platform android --clean', {
    cwd: ROOT,
    stdio: 'inherit',
    env,
  })

  // Step 2: Build debug APK with gradle
  console.log('\nStep 2/3: Building debug APK with Gradle...')
  const androidDir = join(ROOT, 'android')
  execSync('./gradlew assembleDebug', {
    cwd: androidDir,
    stdio: 'inherit',
    env,
  })

  // Step 3: Copy APK to accessible location
  console.log('\nStep 3/3: Copying APK...')
  const apkSource = join(androidDir, 'app/build/outputs/apk/debug/app-debug.apk')
  const outputDir = join(ROOT, 'dist')
  const apkDest = join(outputDir, 'pnyx-devclient.apk')

  if (!existsSync(outputDir)) {
    mkdirSync(outputDir, {recursive: true})
  }

  if (existsSync(apkSource)) {
    cpSync(apkSource, apkDest)
    console.log(`\n✅ APK built successfully!`)
    console.log(`   Location: ${apkDest}`)
    console.log(`\n📋 Next steps:`)
    console.log(`   1. Serve APK for download (scan QR with phone):`)
    console.log(`      bun run dev:serve`)
    console.log(`   2. Or install via USB:`)
    console.log(`      adb install ${apkDest}`)
    console.log(`   3. Start the dev server:`)
    console.log(`      bun run dev`)
    console.log(`   4. Open the app and scan the QR code`)
  } else {
    throw new Error(`APK not found at ${apkSource}`)
  }
}

/**
 * Build development app for iOS.
 */
async function buildIos(): Promise<void> {
  const env = {...process.env, PNYX_BUILD_VARIANT: 'devclient'}

  console.log('\n📱 Building iOS development app...\n')

  // Check if running on macOS
  if (process.platform !== 'darwin') {
    console.error('❌ iOS builds require macOS with Xcode installed.')
    process.exit(1)
  }

  // Step 1: Run expo prebuild
  console.log('Step 1/2: Running expo prebuild...')
  execSync('npx expo prebuild --platform ios --clean', {
    cwd: ROOT,
    stdio: 'inherit',
    env,
  })

  // Step 2: Build with xcodebuild for device
  console.log('\nStep 2/2: Building with xcodebuild...')
  const iosDir = join(ROOT, 'ios')

  // Find the Xcode workspace generated by expo prebuild
  const files = readdirSync(iosDir)
  const found = files.find((f: string) => f.endsWith('.xcworkspace'))
  if (!found) {
    throw new Error('No Xcode workspace found in ios directory')
  }
  const workspace = join(iosDir, found)
  const schemeName = found.replace('.xcworkspace', '')

  console.log(`Using workspace: ${workspace}`)

  // Check if --device flag was passed to target physical device
  const useDevice = process.argv.includes('--device') || process.argv.includes('-d')
  const destination = useDevice ? 'generic/platform=iOS' : 'generic/platform=iOS Simulator'

  if (useDevice) {
    console.log('Building for physical device (requires signing)...')
  } else {
    console.log('Building for iOS Simulator (no signing required)...')
  }

  execSync(
    `xcodebuild -workspace "${workspace}" -scheme "${schemeName}" -configuration Debug -destination '${destination}' -derivedDataPath build`,
    {
      cwd: iosDir,
      stdio: 'inherit',
      env,
    },
  )

  const productDir = useDevice ? 'Debug-iphoneos' : 'Debug-iphonesimulator'
  console.log(`\n✅ iOS build complete!`)
  console.log(`\n📋 Next steps:`)
  if (useDevice) {
    console.log(`   1. Install on your device:`)
    console.log(`      ios-deploy --bundle ios/build/Build/Products/${productDir}/*.app`)
  } else {
    console.log(`   1. Install on simulator:`)
    console.log(`      xcrun simctl install booted ios/build/Build/Products/${productDir}/*.app`)
  }
  console.log(`   2. Start the dev server:`)
  console.log(`      bun run dev`)
  console.log(`   3. Open the app and scan the QR code`)
}

/**
 * Main entry point.
 */
async function main(): Promise<void> {
  const args = process.argv.slice(2)
  const platform = args[0] as Platform

  if (!platform || !['android', 'ios'].includes(platform)) {
    console.log('Usage: bun scripts/build-dev.ts <android|ios>')
    console.log('')
    console.log('Builds a development APK/app with expo-dev-client')
    console.log('that can connect to metro via QR code.')
    process.exit(1)
  }

  console.log(`\n🏗️  Building development build for ${platform}...\n`)

  ensureEnv()

  assertDevEnvComplete()

  if (platform === 'android') {
    await buildAndroid()
  } else {
    await buildIos()
  }
}

main().catch((err) => {
  console.error('\n❌ Build failed:', err.message)
  process.exit(1)
})
